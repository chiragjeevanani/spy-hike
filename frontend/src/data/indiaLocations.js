export const INDIA_STATES = Object.keys(INDIA_STATES_AND_CITIES);

export function getCitiesForState(stateName) {
  if (!stateName) return [];
  return INDIA_STATES_AND_CITIES[stateName] || [];
}

export function formatLocation(city, state) {
  const c = (city || '').trim();
  const s = (state || '').trim();
  if (c && s && c.toLowerCase() !== s.toLowerCase()) {
    return `${c}, ${s}`;
  }
  return c || s || '';
}
